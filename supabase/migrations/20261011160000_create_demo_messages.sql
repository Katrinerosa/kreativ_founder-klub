create table if not exists public.demo_messages (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(author) between 1 and 40),
  message text not null check (char_length(message) between 1 and 280),
  created_at timestamptz not null default now()
);

alter table public.demo_messages enable row level security;

grant select, insert on table public.demo_messages to anon, authenticated;
grant usage, select on sequence public.demo_messages_id_seq to anon, authenticated;

create policy "Anyone can read demo messages"
on public.demo_messages for select
to anon, authenticated
using (true);

create policy "Anyone can add a short demo message"
on public.demo_messages for insert
to anon, authenticated
with check (
  char_length(author) between 1 and 40
  and char_length(message) between 1 and 280
);

insert into public.demo_messages (author, message)
select seed.author, seed.message
from (
  values
    ('Nora', 'Er der nogen, der vil dele dagens vigtigste opgave? Min er at få sendt mit tilbud afsted.'),
    ('Maja', 'Ja! Jeg gør min portfolio færdig i dag. Skal vi tjekke ind igen kl. 14?')
) as seed(author, message)
where not exists (select 1 from public.demo_messages);

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'demo_messages'
  ) then
    alter publication supabase_realtime add table public.demo_messages;
  end if;
end
$$;
